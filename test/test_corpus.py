"""The golden corpus — the test that makes this project trustworthy.

Every file under ``test/corpus`` was generated by ``@adeloi/edi-fixtures``,
which is the library that defines what "broken in a realistic way" means. The
filename states the diagnosis the file must produce. Two properties are
asserted:

**No false positives.** Every clean document must come back with zero findings.
This is the property that decides whether a linter is usable at all: one that
cries wolf on valid input gets switched off, and then it catches nothing.

**No false negatives.** Every broken document must produce its expected code,
and *only* that code. A check that fires on the right file for the wrong reason
is not a working check.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from conftest import CLEAN, EDGE, FAULTS, FLOWS, SCANS, corpus_files, read
from x12doctor import PartnerProfile, diagnose, scan

#: Faults whose fixture also legitimately changes something a second check
#: notices. Each entry is documented, because an undocumented follow-on finding
#: is indistinguishable from a bug.
ALLOWED_FOLLOW_ON: dict[str, set[str]] = {
    # Truncating ISA08 shortens the whole segment, so the interchange also fails
    # its element-count check. Both findings name the same defect from two
    # angles and both are worth printing.
    "A01": set(),
}


def _expected_code(path: Path) -> str:
    """``850_seed42_A02_seCountWrong.edi`` yields ``"A02"``."""
    return path.stem.split("_")[2]


def _fault_name(path: Path) -> str:
    return path.stem.split("_", 3)[3]


# ---------------------------------------------------------------------------
# No false positives
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("path", corpus_files(CLEAN), ids=lambda p: p.stem)
def test_clean_documents_produce_no_findings(path: Path) -> None:
    report = diagnose(read(path), source=str(path))
    assert report.findings == [], (
        f"{path.name} is a clean fixture but produced "
        + "; ".join(f"{f.code} {f.message}" for f in report.findings)
    )
    assert report.ok


@pytest.mark.parametrize("path", corpus_files(CLEAN), ids=lambda p: p.stem)
def test_clean_documents_stay_clean_under_their_partner_profile(
    path: Path, dp_partner: PartnerProfile
) -> None:
    """The profile edi-fixtures generated against must not flag its own output."""
    if path.stem.startswith(("856", "997")):
        # Neither carries the partner REF segments; edi-fixtures only emits
        # them for the 850, 855 and 810.
        pytest.skip("transaction set carries no partner REF segments")
    report = diagnose(read(path), partner=dp_partner, source=str(path))
    assert report.findings == []


def test_clean_flow_scans_without_findings() -> None:
    result = scan(FLOWS / "clean")
    assert result.findings == []
    assert all(entry.report.findings == [] for entry in result.entries)
    assert result.ok


# ---------------------------------------------------------------------------
# No false negatives
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("path", corpus_files(FAULTS), ids=lambda p: p.stem)
def test_fault_produces_its_expected_code(path: Path) -> None:
    expected = _expected_code(path)
    # Only the partner-specific fault needs a profile; running the others
    # without one proves they do not depend on partner configuration.
    partner = (
        PartnerProfile(required_refs=("DP",))
        if _fault_name(path) == "missingRef"
        else PartnerProfile()
    )
    report = diagnose(read(path), partner=partner, source=str(path))

    assert expected in report.codes(), (
        f"{path.name} should be diagnosed as {expected}, got "
        + (
            "; ".join(f"{f.code} {f.message}" for f in report.findings)
            or "no findings at all"
        )
    )


@pytest.mark.parametrize("path", corpus_files(FAULTS), ids=lambda p: p.stem)
def test_fault_produces_only_its_expected_code(path: Path) -> None:
    """A fixture broken one way must not light up unrelated checks."""
    expected = _expected_code(path)
    partner = (
        PartnerProfile(required_refs=("DP",))
        if _fault_name(path) == "missingRef"
        else PartnerProfile()
    )
    report = diagnose(read(path), partner=partner, source=str(path))

    allowed = {expected} | ALLOWED_FOLLOW_ON.get(expected, set())
    unexpected = sorted(set(report.codes()) - allowed)
    assert not unexpected, (
        f"{path.name} should produce only {expected}, but also produced "
        + "; ".join(
            f"{f.code} {f.message}" for f in report.findings if f.code in unexpected
        )
    )


