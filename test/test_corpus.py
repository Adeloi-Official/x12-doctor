def test_duplicate_control_numbers_are_found_across_files() -> None:
    result = scan(SCANS / "A04_duplicateIsaControl")
    assert "A04" in {f.code for f in result.findings}
    # Both files are individually valid; the defect exists only in the pair.
    assert all(entry.report.findings == [] for entry in result.entries)


def test_unique_control_numbers_are_not_reported() -> None:
    result = scan(SCANS / "clean_controls")
    assert result.findings == []


@pytest.mark.parametrize(
    ("directory", "code"),
    [
        ("C02_fa997UnknownGroup", "C02"),
        ("C06_outOfOrderInterchange", "C06"),
        ("D03_asnQtyMismatch", "D03"),
    ],
)
def test_flow_fault_is_found_across_files(directory: str, code: str) -> None:
    result = scan(FLOWS / directory)
    assert code in {f.code for f in result.findings}


def test_rejected_997_is_found_in_the_file_itself() -> None:
    """A rejection is visible in the 997 alone; no pairing is required."""
    result = scan(FLOWS / "C03_fa997Rejected")
    codes = {f.code for entry in result.entries for f in entry.report.findings}
    assert "C03" in codes


def test_missing_997_needs_the_flag() -> None:
    """Nothing in the flow asked to be acknowledged, so the default is quiet."""
    directory = FLOWS / "C05_fa997Missing"
    assert not [f for f in scan(directory).findings if f.code == "C05"]

    demanded = scan(directory, check_acknowledgments=True)
    assert "C05" in {f.code for f in demanded.findings}


def test_missing_997_fixture_really_has_no_acknowledgment() -> None:
    """Guards the fixture itself: the corpus must not have gained a 997."""
    files = corpus_files(FLOWS / "C05_fa997Missing")
    assert files, "the fixture directory is empty"
    assert not any("997" in path.name for path in files)


# ---------------------------------------------------------------------------
# Every fault in the sister library is covered
# ---------------------------------------------------------------------------

#: The 18 faults of @adeloi/edi-fixtures and the code each must produce. This
#: list is the contract between the two projects; a fault added there without a
#: diagnosis here fails this test.
FIXTURE_FAULTS: dict[str, str] = {
    "isaTruncated": "A01",
    "seCountWrong": "A02",
    "controlNumberMismatch": "A03",
    "duplicateIsaControl": "A04",
    "nonstandardSeparators": "A05",
    "uomNonstandard": "B01",
    "impliedDecimals": "B02",
    "dateFormatShort": "B03",
    "cttMismatch": "B04",
    "missingRef": "B05",
    "fa997UnknownGroup": "C02",
    "fa997Rejected": "C03",
    "fa997Missing": "C05",
    "outOfOrderInterchange": "C06",
    "hlOrphan": "D01",
    "ssccInvalid": "D02",
    "asnQtyMismatch": "D03",
    "asnAfterDelivery": "D04",
}


def test_every_fixture_fault_has_a_corpus_file() -> None:
    """Each of the 18 faults must be represented somewhere in the corpus."""
    named = {_fault_name(p) for p in corpus_files(FAULTS)}
    for directory in (FLOWS, SCANS):
        for child in directory.iterdir():
            if child.is_dir() and "_" in child.name:
                named.add(child.name.split("_", 1)[1])

    missing = sorted(set(FIXTURE_FAULTS) - named)
    assert not missing, f"no corpus file exercises: {', '.join(missing)}"


def test_catalog_agrees_with_the_fixture_mapping() -> None:
    """The catalog's own fixture attributions must match this test's table."""
    from x12doctor import CATALOG

    attributed = {
        entry.fixture: entry.code
        for entry in CATALOG.values()
        if entry.fixture is not None
    }
    assert attributed == FIXTURE_FAULTS


