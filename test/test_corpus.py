def test_empty_file_is_reported_as_unusable() -> None:
    report = diagnose(read(EDGE / "empty.edi"))
    assert report.has("A00")
    assert report.doc_type == "unknown"


def test_non_x12_file_reports_only_that() -> None:
    """A CSV must not have its lines reported as malformed segments."""
    report = diagnose(read(EDGE / "not_x12.edi"))
    assert report.codes() == ["A00"]


@pytest.mark.parametrize(
    "name", ["truncated_mid_segment.edi", "no_trailers.edi"]
)
def test_truncated_documents_report_the_missing_trailers(name: str) -> None:
    report = diagnose(read(EDGE / name))
    assert report.has("A10")
    # A truncated file still parses far enough to be recognised.
    assert report.doc_type == "850"
