"""Generate docs/diagnostics.md from the catalog.

``catalog.py`` is the single source of truth. Hand-maintaining a parallel
markdown table guarantees the two drift, and a wrong explanation of why a
document was rejected is worse than no explanation.

    python tools/gen-docs.py            # write the file
    python tools/gen-docs.py --check    # exit 1 if it would change (used in CI)
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from x12doctor.catalog import CATALOG, CATEGORIES, Diagnostic  # noqa: E402

OUTPUT = ROOT / "docs" / "diagnostics.md"
WIDTH = 74

HEADER = """\
# The diagnostic catalog

<!--
  Generated from src/x12doctor/catalog.py by tools/gen-docs.py.
  Do not edit this file by hand; edit the catalog and regenerate.
-->

Every diagnosis x12-doctor can make. Each one states what it checks, why real
integrations produce it, and what to change — because a code and a line number
is not an answer to "why did my order not arrive".

Eighteen of these mirror a fault in
[`@adeloi/edi-fixtures`](https://github.com/Adeloi-Official/edi-fixtures) one
for one. That library generates the broken document; this one diagnoses it. The
correspondence is asserted by the test suite in both directions, so a fault
added there without a diagnosis here fails the build.

`x12doctor codes` prints this catalog in the terminal, and `x12doctor codes A02`
explains a single entry.

## Severity

| Severity | Meaning |
|---|---|
| `error` | The document is wrong. A partner will reject it, or has. |
| `warning` | Legal, but a common cause of rejection or silent misreading. |
| `info` | Worth knowing. Normal in some workflows. |

`--fail-on` decides which of these makes the command exit non-zero. It defaults
to `error`.
"""

FOOTER = """\
## Adding a diagnosis

Add an entry to `CATALOG` in `src/x12doctor/catalog.py`, raise it from a check
with `catalog.make_finding()`, then regenerate this file:

```sh
python tools/gen-docs.py
```

The test suite asserts that every catalog entry is raised somewhere, that every
raised code is in the catalog, and that this file is not stale.
"""


def wrap(text: str) -> str:
    return "\n".join(textwrap.wrap(text, width=WIDTH, break_on_hyphens=False))


def render_entry(entry: Diagnostic) -> str:
    lines = [f"### `{entry.code}` — {entry.title}", ""]
    lines.append(f"**Severity:** `{entry.severity}` · **Applies to:** {entry.scope}")
    lines.append("")
    lines.append("**What it checks:** " + wrap(entry.what).lstrip())
    lines.append("")
    lines.append("**Why it happens in production:** " + wrap(entry.why).lstrip())
    lines.append("")
    lines.append("**How to fix it:** " + wrap(entry.hint).lstrip())

    if entry.fixture:
        lines.append("")
        lines.append(
            f"**Matching fixture:** `faults.{entry.fixture}()` in "
            "`@adeloi/edi-fixtures` produces a document that triggers this."
        )

    return "\n".join(lines)


def render() -> str:
    parts = [HEADER, ""]

    parts.append("## Contents")
    parts.append("")
    for letter, name in CATEGORIES.items():
        entries = [e for e in CATALOG.values() if e.category == letter]
        if not entries:
            continue
        codes = " · ".join(f"[`{e.code}`](#{_anchor(e)})" for e in entries)
        parts.append(f"**{letter} — {name}**  \n{codes}")
        parts.append("")

    for letter, name in CATEGORIES.items():
        entries = [e for e in CATALOG.values() if e.category == letter]
        if not entries:
            continue
        parts.append("---")
        parts.append("")
        parts.append(f"## {letter} — {name}")
        parts.append("")
        for entry in entries:
            parts.append(render_entry(entry))
            parts.append("")

    parts.append("---")
    parts.append("")
    parts.append(FOOTER)

    return "\n".join(parts).rstrip() + "\n"


def _anchor(entry: Diagnostic) -> str:
    """GitHub's anchor for ``### `A02` — SE segment count is wrong``."""
    text = f"{entry.code} — {entry.title}".lower()
    keep = [c for c in text if c.isalnum() or c in " -"]
    return "".join(keep).replace(" ", "-")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the file is out of date instead of writing it",
    )
    args = parser.parse_args()

    rendered = render()

    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date", file=sys.stderr)
            return 1
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(CATALOG)} diagnostics)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
